export default async function ({ page, app, out, root, sleep }) {
  await app.evaluate(({ ipcMain }) => {
    ipcMain.removeHandler('game:fileref')
    ipcMain.handle('game:fileref', () => '/tmp/lantern-save-test.glksave')
  })
  const type = async (cmd) => {
    await page.waitForSelector('.line-input', { timeout: 6000 })
    await page.fill('.line-input', cmd)
    await page.press('.line-input', 'Enter')
    await sleep(450)
  }
  await page.evaluate((p) => window.__lantern.openStory(p), `${root}/test/stories/advent.ulx`)
  await sleep(1500)
  for (const c of ['e', 'take lamp', 'w', 's', 's']) await type(c)
  await type('save')
  await sleep(800)
  const fs = await import('node:fs')
  console.log('save exists', fs.existsSync('/tmp/lantern-save-test.glksave'))
  await type('n'); await type('n')
  await type('restore')
  await sleep(800)
  const txt = await page.evaluate(() => window.__lantern.state.display.transcriptText().slice(-300))
  console.log('after restore:', txt.replace(/\n/g, ' | '))
  // travel by map
  const target = await page.evaluate(() => window.__lantern.state.automap.list().find(r => r.name === 'Inside Building').id)
  await page.evaluate((id) => window.__lantern.travelTo(id), target)
  await sleep(3000)
  console.log('now in', await page.evaluate(() => window.__lantern.state.automap.current.name))
  // note via meta command
  await type('/note Lampe hier gefunden')
  await page.evaluate(() => window.__lantern.command('help'))
  await sleep(300)
  await page.screenshot({ path: `${out}/feat-help.png` })
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.__lantern.command('settings'))
  await sleep(300)
  await page.screenshot({ path: `${out}/feat-settings.png` })
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.__lantern.command('style'))
  await sleep(300)
  await page.screenshot({ path: `${out}/feat-style.png` })
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.__lantern.command('toggle-map'))
  await sleep(600)
  await page.fill('.line-input', 'exa')
  await page.dispatchEvent('.line-input', 'input')
  await sleep(200)
  await page.screenshot({ path: `${out}/feat-nomap.png` })
  const wins = await page.evaluate(() => [...window.__lantern.state.display.windows.values()].map(w => `${w.type}:${Math.round(w.width)}x${Math.round(w.height)}`))
  console.log('wins after hide', wins)
}
